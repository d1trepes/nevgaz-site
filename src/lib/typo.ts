/** Неразрывный пробел после коротких слов (в, на, по, и, а, с, к, не…) и перед тире — для текстов из данных. */
export const nb = (s: string) =>
  s
    .replace(/(^|[\s(«])([А-Яа-яЁё]{1,3})\s+/g, '$1$2 ')
    .replace(/(^|[\s(«])([А-Яа-яЁё]{1,3})\s+/g, '$1$2 ') // второй проход для «и в», «а с»
    .replace(/\s+—/g, ' —')
    .replace(/(\d)\s+(?=[\d₽])/g, '$1 ')
    .replace(/(\d)\s+(?=(тыс|руб|лет|дн|м)\b)/g, '$1 ');
